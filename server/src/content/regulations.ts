const STOP = new Set(
  "и в во на по для что как это от до не ни о об из за к ко с со у а но или если ли же бы при над под про я мы вы он она они мой моя мне меня нужно надо хочу можно ли".split(
    " ",
  ),
);

function tokens(value: string): string[] {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^a-zа-я0-9]+/i)
    .map((word) => word.trim())
    .filter((word) => word.length > 2 && !STOP.has(word));
}

function stem(word: string) {
  return word.length > 6 ? word.slice(0, 6) : word;
}

export function searchRegulations(query: string, limit = 3) {
  const qTokens = tokens(query).map(stem);
  return REGULATION_DOCS.map((doc) => {
    const titleTokens = tokens(doc.title).map(stem);
    const bodyTokens = tokens(doc.body).map(stem);
    let score = 0;
    for (const token of qTokens) {
      if (titleTokens.some((item) => item.includes(token) || token.includes(item))) score += 4;
      score += Math.min(6, bodyTokens.filter((item) => item.includes(token) || token.includes(item)).length);
    }
    return { doc, score };
  })
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(({ doc }) => ({
      slug: doc.slug,
      title: doc.title,
      excerpt: excerpt(doc.body, qTokens),
    }));
}

function excerpt(body: string, qTokens: string[]) {
  const parts = body.split(/\n+/).map((part) => part.trim()).filter(Boolean);
  const hit =
    parts.find((part) => {
      const stemmed = tokens(part).map(stem);
      return qTokens.some((token) => stemmed.some((item) => item.includes(token) || token.includes(item)));
    }) ?? parts[0];
  return hit.length > 320 ? `${hit.slice(0, 317)}…` : hit;
}
